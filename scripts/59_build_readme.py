"""Step 59: build README.md from docs/readme/README.template.md.

The README is a narrative with numbered figures. The template holds the text and each figure's
legend; this script numbers the figures in order of appearance, resolves cross-references, inserts
the images and the performance tables, and appends a figure index that maps README numbers to the
figure files (whose own captions carry every statistic).

Template syntax
    ::: figure U23                  a main figure (file id: U23, S4, T7, X1, M1, O1, or a results/summary stem)
    title: ...                      optional; default = the title in the figure's caption file
    (a) ... (b) ...                 the legend body
    :::
    ::: sfigure U5 ... :::          a supplementary figure, numbered separately
    {{ref:U23}}                     -> "Figure 12" or "Supplementary Figure 3"
    {{n:U23}}                       -> "12" (the bare number)
    {{table:STATUS}}, {{table:TYPE}} -> the headline tables of scripts/06_summarise_results.py

Usage: python scripts/59_build_readme.py
"""
from __future__ import annotations

import importlib.util
import re
import textwrap
from pathlib import Path

from _common import log

REPO = Path(__file__).resolve().parents[1]
TEMPLATE = REPO / "docs" / "readme" / "README.template.md"
FIG_DIRS = ["overview", "cancer_type", "tumour_status", "subtype", "manuscript", "across_tasks"]
BLOCK = re.compile(r"^::: (figure|sfigure) (\S+)\n(.*?)\n:::$", re.S | re.M)
MAX_W, PX_PER_IN = 900, 125


def _load(name: str, file: str):
    spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(file))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def find(fid: str) -> Path:
    """The PNG of a figure id: results/figures/<dir>/<id>_*.png, or results/summary/<id>.png."""
    for d in FIG_DIRS:
        hits = sorted((REPO / "results" / "figures" / d).glob(f"{fid}_*.png"))
        if hits:
            return hits[0]
    p = REPO / "results" / "summary" / f"{fid}.png"
    if p.exists():
        return p
    raise FileNotFoundError(f"no figure file for {fid}")


def caption_title(png: Path) -> str:
    first = Path(str(png)[:-4] + ".caption.md").read_text().strip()
    m = re.match(r"\*\*Figure [A-Z]+\d+\. (.+?)\*\*", first, re.S)
    if not m:
        raise ValueError(f"{png.name}: caption has no 'Figure Xn. Title.' line; give a title: in the template")
    return " ".join(m.group(1).split())


def width(png: Path) -> int:
    from PIL import Image
    im = Image.open(png)
    dpi = (im.info.get("dpi") or (400, 400))[0]
    return int(min(MAX_W, round(im.size[0] / dpi * PX_PER_IN)))


def wrap(text: str, w: int = 100) -> str:
    return "\n".join(textwrap.wrap(" ".join(text.split()), w, break_on_hyphens=False))


def tables() -> dict[str, str]:
    import pandas as pd

    from ctsm.config import load_config
    m06 = _load("summarise06", "06_summarise_results.py")
    cfg = load_config()
    ts = pd.read_csv(REPO / "results" / "summary" / "tumor_status_metrics.csv")      # written by step 06
    ct = pd.read_csv(REPO / "results" / "summary" / "cancer_type_metrics.csv")
    out = {}
    for key, lines in m06.readme_blocks(cfg, ts, ct).items():
        head = f"<!-- RESULTS-{key}:START (generated by scripts/06_summarise_results.py) -->"
        out[key] = "\n".join([head, *lines, "", f"<!-- RESULTS-{key}:END -->"])
    return out


def build() -> str:
    tpl = TEMPLATE.read_text()
    blocks = list(BLOCK.finditer(tpl))
    num, kind = {}, {}
    counter = {"figure": 0, "sfigure": 0}
    for b in blocks:
        k, fid = b.group(1), b.group(2)
        if fid in num:
            raise ValueError(f"{fid} placed twice")
        counter[k] += 1
        num[fid], kind[fid] = counter[k], k
    label = lambda fid: ("Figure" if kind[fid] == "figure" else "Supplementary Figure") + f" {num[fid]}"
    index = []

    def render(b: re.Match) -> str:
        k, fid, body = b.group(1), b.group(2), b.group(3).strip()
        png = find(fid)
        title = None
        if body.startswith("title:"):
            first, _, body = body.partition("\n")
            title = first[len("title:"):].strip()
        title = title or caption_title(png)
        rel = png.relative_to(REPO).as_posix()
        stem = rel[:-4]
        index.append((label(fid), fid, title, rel))
        alt = f"{label(fid)}: {title}".replace('"', "'")
        legend = wrap(f"**{label(fid)}. {title}** {body}")
        src = (f"<sub>Figure file {fid}: [caption with every statistic]({stem}.caption.md) · "
               f"[plotted values]({stem}.csv)</sub>")
        return f'<img src="{rel}" width="{width(png)}" alt="{alt}">\n\n{legend}\n\n{src}'

    out = BLOCK.sub(render, tpl)
    out = re.sub(r"\{\{ref:(\S+?)\}\}", lambda m: label(m.group(1)), out)
    out = re.sub(r"\{\{n:(\S+?)\}\}", lambda m: str(num[m.group(1)]), out)
    tab = tables()
    out = re.sub(r"\{\{table:(\w+)\}\}", lambda m: tab[m.group(1)], out)
    left = re.findall(r"\{\{[^}]*\}\}", out)
    if left:
        raise ValueError(f"unresolved: {left}")
    rows = ["| README | File | Title |", "|---|---|---|"]
    rows += [f"| {lab} | [{fid}]({rel}) | {t} |" for lab, fid, t, rel in index]
    out = out.replace("<!-- FIGURE-INDEX -->", "\n".join(rows))
    head = ("<!-- Generated by scripts/59_build_readme.py from docs/readme/README.template.md. "
            "Edit the template and rerun the script; edits made here are overwritten. -->\n")
    log(f"README: {counter['figure']} figures, {counter['sfigure']} supplementary figures")
    return head + out


def main() -> None:
    (REPO / "README.md").write_text(build())


if __name__ == "__main__":
    main()
